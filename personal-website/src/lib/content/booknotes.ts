export function getBookNote(slug: string) {
	return bookNotes.find((book) => book.slug === slug);
}

export function getRelatedBookNotes(slug: string, limit = 4) {
	const currentIndex = bookNotes.findIndex((book) => book.slug === slug);
	const ordered =
		currentIndex === -1
			? bookNotes
			: [...bookNotes.slice(currentIndex + 1), ...bookNotes.slice(0, currentIndex)];
	return ordered.filter((book) => book.slug !== slug).slice(0, limit);
}
